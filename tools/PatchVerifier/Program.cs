using System.Runtime.Loader;
using System.Text;

namespace PatchVerifier;

/// <summary>
/// Usage:
///   PatchVerifier refs    --mod DIR --props FILE      write MSBuild props mirroring the loader's compile setup
///   PatchVerifier compile --mod DIR --out DLL         game-exact compile (+ Source/Core purity check)
///   PatchVerifier verify  --mod DIR --dll DLL         manifest, security, Harmony patches, data-sheet contents
///   PatchVerifier all     --mod DIR --out DLL         compile then verify
/// Options: --managed DIR (default $UBOAT_MANAGED or the Steam library path), --game-version 2026.1
/// Exit code: 0 ok, 1 errors found, 2 usage / environment problem.
/// </summary>
public static class Program
{
    public static int Main(string[] argv)
    {
        if (argv.Length == 0)
        {
            Console.WriteLine("usage: PatchVerifier refs|compile|verify|all --mod DIR [--out DLL] [--dll DLL] [--props FILE] [--managed DIR] [--game-version V]");
            return 2;
        }
        var opts = ParseOptions(argv.Skip(1).ToArray());
        string cmd = argv[0];
        string modDir = Path.GetFullPath(opts.GetValueOrDefault("mod") ?? "mod");
        string gameVersion = opts.GetValueOrDefault("game-version") ?? "2026.1";

        GameEnvironment env;
        RoslynSettingsAsset settings;
        try
        {
            env = GameEnvironment.FromEnvironment(opts.GetValueOrDefault("managed"));
            InstallGameAssemblyResolver(env.ManagedDir);
            settings = RoslynSettingsAsset.Load(env.ResourcesAssets);
        }
        catch (Exception e)
        {
            Console.WriteLine("ERROR " + e.Message);
            return 2;
        }

        var report = new Report();
        report.Section($"environment: {env.ManagedDir}");
        settings.Print(report);
        var manifest = ManifestCheck.Run(modDir, gameVersion, report);

        switch (cmd)
        {
            case "refs":
                WriteProps(env, settings, manifest, opts.GetValueOrDefault("props") ?? Path.Combine(modDir, "..", "build", "generated", "GameCompile.props"), report);
                break;
            case "compile":
                GameCompiler.Compile(env, settings, modDir, manifest, Required(opts, "out"), report);
                break;
            case "verify":
                Verify(env, settings, manifest, modDir, Required(opts, "dll"), report);
                break;
            case "all":
                string dll = Required(opts, "out");
                if (GameCompiler.Compile(env, settings, modDir, manifest, dll, report))
                    Verify(env, settings, manifest, modDir, dll, report);
                break;
            default:
                Console.WriteLine("unknown command " + cmd);
                return 2;
        }

        Console.WriteLine($"== result: {report.Errors} error(s), {report.Warnings} warning(s)");
        return report.Errors > 0 ? 1 : 0;
    }

    private static void Verify(GameEnvironment env, RoslynSettingsAsset settings, ManifestCheck.Result manifest, string modDir, string dll, Report report)
    {
        if (!File.Exists(dll))
        {
            report.Error("compiled mod not found: " + dll);
            return;
        }
        SecurityCheck.Run(settings, manifest.Permissions, dll, report);
        using (var hv = new HarmonyVerifier(env, dll, report))
            hv.Run();
        DataSheetCheck.Run(env, modDir, dll, report);
    }

    private static void WriteProps(GameEnvironment env, RoslynSettingsAsset settings, ManifestCheck.Result manifest, string path, Report report)
    {
        report.Section("MSBuild props for build/ModCompile.csproj");
        var refs = env.ResolveLoaderReferences(manifest.Permissions, settings, report);
        int lang = settings.LanguageVersion;
        string langVersion = lang switch
        {
            0 => "7", // LanguageVersion.Default maps to C# 7.0 in Roslyn 2.10
            int.MaxValue => "7.3",
            int.MaxValue - 1 => "7",
            _ => lang >= 100 ? $"{lang / 100}.{lang % 100}" : lang.ToString(),
        };
        var sb = new StringBuilder();
        sb.AppendLine("<Project>");
        sb.AppendLine("  <!-- GENERATED by tools/PatchVerifier refs from the game's loader + RoslynCSharpSettings. Do not edit. -->");
        sb.AppendLine("  <PropertyGroup>");
        sb.AppendLine($"    <AssemblyName>{manifest.AssemblyName}</AssemblyName>");
        sb.AppendLine($"    <LangVersion>{langVersion}</LangVersion>");
        sb.AppendLine($"    <DefineConstants>{string.Join(";", LoaderModel.DefineSymbols)}</DefineConstants>");
        sb.AppendLine($"    <WarningLevel>{settings.WarningLevel}</WarningLevel>");
        sb.AppendLine($"    <Optimize>{(settings.AllowOptimizeCode ? "true" : "false")}</Optimize>");
        sb.AppendLine($"    <AllowUnsafeBlocks>{((manifest.Permissions & LoaderModel.SecurityOptions.NativeAccess) != 0 ? "true" : "false")}</AllowUnsafeBlocks>");
        sb.AppendLine("  </PropertyGroup>");
        sb.AppendLine("  <ItemGroup>");
        foreach (string r in refs)
            sb.AppendLine($"    <Reference Include=\"{Path.GetFileNameWithoutExtension(r)}\"><HintPath>{r}</HintPath><Private>false</Private></Reference>");
        sb.AppendLine("  </ItemGroup>");
        sb.AppendLine("</Project>");
        Directory.CreateDirectory(Path.GetDirectoryName(Path.GetFullPath(path))!);
        File.WriteAllText(path, sb.ToString());
        report.Ok($"{refs.Count} references, LangVersion {langVersion} -> {Path.GetFullPath(path)}");
    }

    private static string Required(Dictionary<string, string> opts, string key) =>
        opts.GetValueOrDefault(key) ?? throw new ArgumentException($"--{key} is required");

    private static Dictionary<string, string> ParseOptions(string[] args)
    {
        var d = new Dictionary<string, string>();
        for (int i = 0; i < args.Length; i++)
            if (args[i].StartsWith("--") && i + 1 < args.Length) d[args[i].Substring(2)] = args[++i];
        return d;
    }

    /// <summary>Lets Trivial.CodeSecurity (and its Cecil copy) load from the game's Managed folder.</summary>
    private static void InstallGameAssemblyResolver(string managed)
    {
        AssemblyLoadContext.Default.Resolving += (ctx, name) =>
        {
            if (name.Name is null || !(name.Name.StartsWith("Trivial.") || name.Name.StartsWith("UnityEngine") || name.Name == "FastExcel")) return null;
            string p = Path.Combine(managed, name.Name + ".dll");
            return File.Exists(p) ? ctx.LoadFromAssemblyPath(p) : null;
        };
    }
}
